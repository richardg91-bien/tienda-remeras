BEGIN;

CREATE TABLE IF NOT EXISTS public.payment_webhook_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider TEXT NOT NULL CHECK (provider = 'mercadopago'),
  event_id TEXT NOT NULL,
  request_id TEXT NOT NULL,
  payment_id TEXT NOT NULL,
  event_type TEXT NOT NULL,
  order_id UUID REFERENCES public.orders(id) ON DELETE SET NULL,
  processing_result TEXT NOT NULL DEFAULT 'received'
    CHECK (processing_result IN ('received', 'applied', 'unmatched', 'failed')),
  received_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  processed_at TIMESTAMPTZ,
  CONSTRAINT payment_webhook_events_provider_event_unique UNIQUE (provider, event_id),
  CONSTRAINT payment_webhook_events_provider_request_unique UNIQUE (provider, request_id)
);

CREATE INDEX IF NOT EXISTS idx_payment_webhook_events_payment_id
  ON public.payment_webhook_events (provider, payment_id);

REVOKE ALL ON public.payment_webhook_events FROM PUBLIC, anon, authenticated;
ALTER TABLE public.payment_webhook_events ENABLE ROW LEVEL SECURITY;
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = 'payment_webhook_events'
      AND policyname = 'payment_webhook_events_deny_clients'
  ) THEN
    CREATE POLICY payment_webhook_events_deny_clients
      ON public.payment_webhook_events
      FOR ALL TO PUBLIC
      USING (false)
      WITH CHECK (false);
  END IF;
END $$;

COMMIT;
